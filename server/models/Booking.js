import mongoose from "mongoose";
const {ObjectId} = mongoose.Schema.Types

const bookingSchema = new mongoose.Schema({
    car: {type: ObjectId, ref: "Car", required: true},
    user: {type: ObjectId, ref: "User", required: true},
    owner: {type: ObjectId, ref: "User", required: true},
    pickupDate: {type: Date, required: true},
    returnDate: {type: Date, required: true},
    status: {type: String, enum: ["pending", "pending_payment", "payment_failed", "confirmed", "active", "completed", "cancelled", "rejected", "refund_pending", "refunded"], default: "pending"},
    price: {type: Number, required: true},
    rentalDays: {type: Number, required: true, default: 1},
    baseAmount: {type: Number, required: true, default: 0},
    discountAmount: {type: Number, default: 0},
    rentalAmount: {type: Number, required: true, default: 0},
    securityDeposit: {type: Number, default: 0},
    totalAmount: {type: Number, required: true, default: 0},
    handoverOption: { type: String, enum: ["renter_pickup", "owner_delivery"], default: "renter_pickup" },
    deliveryFee: { type: Number, default: 0, min: 0 },
    paymentStatus: {type: String, enum: ["not_required", "pending", "paid", "failed", "refund_pending", "refund_failed", "partially_refunded", "refunded"], default: "not_required"},
    paymentId: {type: String, default: ""},
    cancellationRefundAmount: { type: Number, default: 0, min: 0 },
    cancellationRefundStatus: { type: String, enum: ["not_applicable", "pending", "processed", "failed"], default: "not_applicable" },
    cancellationRefundFailureReason: { type: String, default: "" },
    cancellationRefundInitiatedAt: { type: Date },
    cancellationRefundProcessedAt: { type: Date },
    securityDepositStatus: { type: String, enum: ["not_applicable", "pending", "held", "refund_pending", "refund_failed", "refunded", "partially_refunded", "forfeited"], default: "not_applicable" },
    additionalPaymentStatus: { type: String, enum: ["not_required", "pending", "paid", "failed"], default: "not_required" },
    settlementStatus: { type: String, enum: ["pending", "settled"], default: "pending" },
    pickupLocation: {type: String, default: ""},
    dropLocation: {type: String, default: ""},
    pickupCoordinates: { latitude: { type: Number, min: -90, max: 90 }, longitude: { type: Number, min: -180, max: 180 } },
    dropCoordinates: { latitude: { type: Number, min: -90, max: 90 }, longitude: { type: Number, min: -180, max: 180 } },
    routeDistanceKm: {type: Number, default: 0},
    routeDurationMinutes: {type: Number, default: 0},
    cancelledAt: {type: Date},
    completedAt: {type: Date},
    actualReturnDate: {type: Date},
    startOdometerKm: { type: Number, default: 0, min: 0 },
    actualReturnOdometerKm: { type: Number, min: 0 },
    includedKmTotal: { type: Number, default: 0, min: 0 },
    actualKm: { type: Number, default: 0, min: 0 },
    extraKm: { type: Number, default: 0, min: 0 },
    extraKmAmount: { type: Number, default: 0, min: 0 },
    lateHours: { type: Number, default: 0, min: 0 },
    lateReturnAmount: { type: Number, default: 0, min: 0 },
    totalAdditionalCharges: { type: Number, default: 0, min: 0 },
    depositAppliedAmount: { type: Number, default: 0, min: 0 },
    depositRefundAmount: { type: Number, default: 0, min: 0 },
    additionalAmountDue: { type: Number, default: 0, min: 0 },
    settledAt: { type: Date },
    invoiceNumber: { type: String, default: "" },
    renterNote: {type: String, default: '', maxlength: 500},
    ownerNote: {type: String, default: '', maxlength: 500},
    handoverCode: {type: String, required: true, default: () => String(Math.floor(100000 + Math.random() * 900000))},
    renterReady: {type: Boolean, default: false},
    ownerReady: {type: Boolean, default: false}
},{timestamps: true})

const Booking = mongoose.model('Booking', bookingSchema)

export default Booking
