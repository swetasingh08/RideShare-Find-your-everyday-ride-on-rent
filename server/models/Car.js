import mongoose from "mongoose";
const {ObjectId} = mongoose.Schema.Types

const carSchema = new mongoose.Schema({
    owner: {type: ObjectId, ref: 'User'},
    brand: {type: String, required: true},
    model: {type: String, required: true},
    variant: {type: String, default: ''},
    image: {type: String, required: true},
    images: {type: [String], default: []},
    year: {type: Number, required: true},
    registrationYear: {type: Number},
    category: {type: String, required: true},
    seating_capacity: {type: Number, required: true},
    fuel_type: { type: String, required: true, enum: ['Petrol', 'Diesel', 'CNG', 'Electric', 'Hybrid', 'Gas'] },
    evRangeKm: {type: Number, default: 0},
    chargingType: {type: String, default: ''},
    transmission: { type: String, required: true },
    pricePerDay: { type: Number, required: true },
    pricePerHour: {type: Number, default: 0},
    weeklyDiscount: {type: Number, default: 0},
    monthlyDiscount: {type: Number, default: 0},
    securityDeposit: {type: Number, default: 0},
    includedKmPerDay: {type: Number, default: 0},
    extraKmCharge: {type: Number, default: 0},
    lateReturnCharge: {type: Number, default: 0},
    deliveryAvailable: {type: Boolean, default: false},
    deliveryFee: {type: Number, default: 0, min: 0},
    minRentalDays: {type: Number, default: 1},
    maxRentalDays: {type: Number, default: 30},
    location: { type: String, required: true },
    pickupAddress: { type: String, default: '' },
    pickupLocality: {type: String, default: ''},
    landmark: {type: String, default: ''},
    pickupOptions: {type: [String], default: []},
    coordinates: { latitude: { type: Number, min: -90, max: 90 }, longitude: { type: Number, min: -180, max: 180 } },
    availableFrom: {type: Date},
    availableUntil: {type: Date},
    pickupTime: {type: String, default: ''},
    returnTime: {type: String, default: ''},
    instantBooking: {type: Boolean, default: false},
    approvalRequired: {type: Boolean, default: true},
    minDriverAge: {type: Number, default: 21},
    minDrivingExperience: {type: Number, default: 2},
    requiredDocuments: {type: [String], default: ['Driving License', 'Government ID']},
    rentalRules: {type: [String], default: []},
    features: {type: [String], default: []},
    odometerKm: {type: Number, default: 0},
    condition: {type: String, default: 'Good'},
    lastServiceDate: {type: Date},
    nextServiceDue: {type: Date},
    knownIssues: {type: String, default: ''},
    documents: {
        type: [{ documentType: { type: String, required: true }, url: { type: String, required: true } }],
        default: [],
    },
    registrationNumber: {type: String, default: ''},
    vin: {type: String, default: ''},
    insuranceProvider: {type: String, default: ''},
    insuranceExpiry: {type: Date},
    pucExpiry: {type: Date},
    verificationStatus: {type: String, enum: ['pending', 'verified', 'rejected'], default: 'pending'},
    description: { type: String, required: true },
    isAvaliable: {type: Boolean, default: true},
    bookingLockToken: {type: String, default: '', select: false},
    bookingLockUntil: {type: Date, default: null, select: false},
},{timestamps: true})

const Car = mongoose.model('Car', carSchema)

export default Car
